String translit(String s) {
  final t = s.toLowerCase();
  final sb = StringBuffer();
  var i = 0;
  while (i < t.length) {
    if (i + 4 <= t.length && _tri.containsKey(t.substring(i, i + 4))) {
      sb.write(_tri[t.substring(i, i + 4)]); i += 4; continue;
    }
    if (i + 3 <= t.length && _tri.containsKey(t.substring(i, i + 3))) {
      sb.write(_tri[t.substring(i, i + 3)]); i += 3; continue;
    }
    if (i + 2 <= t.length && _bi.containsKey(t.substring(i, i + 2))) {
      sb.write(_bi[t.substring(i, i + 2)]); i += 2; continue;
    }
    final c = t[i];
    sb.write(_uni[c] ?? c);
    i++;
  }
  return sb.toString();
}

String _cap(String s) => s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);

String localTranslate(String en) {
  final out = <String>[];
  for (final raw in en.split(RegExp(r'\s+'))) {
    final clean = raw.replaceAll(RegExp(r'[^A-Za-z0-9]'), '');
    if (clean.isEmpty) continue;
    final low = clean.toLowerCase();
    if (_skip.contains(low) && out.isNotEmpty) continue;
    if (_w.containsKey(low)) {
      out.add(_w[low]!);
    } else if (RegExp(r'^[0-9]+$').hasMatch(clean)) {
      out.add(clean);
    } else {
      out.add(_cap(translit(clean)));
    }
  }
  if (out.isEmpty) return en;
  return _cap(out.join(' '));
}

String ak(String s) {
  final k = nk(s);
  if (k.isNotEmpty) return _actorAliases[k] ?? k;
  final rl = s.trim().toLowerCase().replaceAll('ё', 'е');
  if (_ruActorAliases.containsKey(rl)) return _ruActorAliases[rl]!;
  for (final e in _ruActorAliases.entries) {
    if (rl.contains(e.key) || e.key.contains(rl)) return e.value;
  }
  return rl.replaceAll(RegExp(r'[^а-яa-z0-9]+'), '');
}

